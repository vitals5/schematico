import assert from 'node:assert/strict';
import {packCircuitUnits} from './circuitPacking';
const block=(id:string)=>({id:'block-'+id,width:80,height:60,children:[{id,x:0,y:0,width:80,height:60}]});
const units=[[block('p1'),block('c1')],[block('p2'),block('c2')]];
const source=JSON.stringify(units);
const position=(n:ReturnType<typeof packCircuitUnits>,id:string)=>n!.children!.find(c=>c.id===id)!;
const large=packCircuitUnits('root',units,400,200,16,32)!;
assert.equal(large.width,384);
assert.equal(position(large,'c1').x!-position(large,'p1').x!-80,16);
assert.equal(position(large,'p2').x!-position(large,'c1').x!-80,32,'Independent units have a larger separator');
const tight=packCircuitUnits('root',units,375,200,16,32)!;
assert.equal(tight.width,368);assert.equal(tight.height,60,'Larger spacing must not create an avoidable extra row');
const short=packCircuitUnits('root',units,300,145,16,32)!;
assert.equal(short.height,136,'Height budget restores compact spacing');
const wrapped=packCircuitUnits('root',units,300,180,16,32)!;
assert.equal(position(wrapped,'p2').y,92);
assert.equal(position(wrapped,'p2').y,position(wrapped,'c2').y,'Pairs wrap together');
assert.equal(packCircuitUnits('root',units,300,130,16,32),undefined,'Neither spacing may exceed available height');
const narrow=packCircuitUnits('root',units,100,400,16,32)!;
assert.deepEqual(new Set(narrow.children!.map(c=>c.id)),new Set(['p1','c1','p2','c2']),'Oversized pairs retain all individual blocks');
assert.equal(JSON.stringify(units),source);
console.log('✓ Distinct internal/external circuit spacing, compact width/height fallback, whole-pair wrapping, oversize fallback and immutable input');
