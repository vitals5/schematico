add(project,'independent');
page.groups=[{id:'inner',members:strip.slice(0,5).map(id=>({kind:'component',id}))},{id:'strip',members:[{kind:'group',id:'inner'},...strip.slice(5).map(id=>({kind:'component' as const,id}))]}];
