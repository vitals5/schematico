const u16 = (n: number) => { const b = Buffer.alloc(2); b.writeUInt16LE(n); return b; }, u32 = (n: number) => { const b = Buffer.alloc(4); b.writeUInt32LE(n); return b; };
const tag = (id: number, data: Uint8Array) => Buffer.concat([u16(id), data]);
const str = (id: number, value: string) => tag(id, Buffer.from(value + '\0'));
const prop = (id: number, value: string) => tag(id, Buffer.concat([u16(0), Buffer.from(value + '\0')]));
const record = (id: number, type: number, body: Uint8Array) => Buffer.concat([u16(0xea61), u16(type), u32(id), body]);
function table(rows: Buffer[], size: number) {
    const data = Buffer.alloc(size * rows.length), index = Buffer.alloc(rows.length * 7);
    rows.forEach((r, i) => { const slot = data.subarray(i * size, (i + 1) * size); slot.writeUInt32BE(r.readUInt32LE(4)); slot.writeUInt16BE(r.readUInt16LE(2), 4); r.copy(slot, 24); index[i * 7 + 2] = r.readUInt32LE(4) & 255; index.writeUInt32BE(i + 1, i * 7 + 3); });
    return { data, index };
}
