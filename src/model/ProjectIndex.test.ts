import assert from 'node:assert/strict';
import { fixture, add } from '../layout/testing/fixture';
import { ProjectIndex, scopedDesignation } from './ProjectIndex';
import { CrossReferenceEngine } from './CrossReferenceEngine';
import { referenceTargets } from './CrossReferenceNavigation';
import { collectPlausibilityMessages } from './ProjectInspection';
import { TerminalDiagramGenerator } from '../reports/TerminalDiagram';
import { McpToolRegistry } from '../ai/mcp-tools';
const p = fixture();
p.pages[0].higherLevel = '=A';
p.pages[0].location = '+L';
const coil = add(p, 'coil', 'contactor_coil', 100, 100);
coil.bmk = ' -K1 ';
coil.higherLevelFunction = 'A';
coil.mountingLocation = 'L';
const contact = add(p, 'contact', 'contact_no', 200, 100);
contact.bmk = '-K1';
// Use project-owned definitions, independent of global active-project state.
p.symbolLibrary = [{ id: 'contact-test', name: 'Contact', description: '', standard: '', category: 'relays', defaultBmkPrefix: 'K', defaultFunctionText: '', width: 16, height: 16, svgContent: '', isContact: true, contactType: 'NO', pins: [{ id: '13', name: '13', x: 8, y: 0, direction: 'top' }, { id: '14', name: '14', x: 8, y: 16, direction: 'bottom' }] }];
contact.symbolId = 'contact-test';
contact.pins = { '13': {}, '14': {} };
const other = structuredClone(p.pages[0]);
other.id = 'other';
other.pageNumber = '2';
other.location = '+Elsewhere';
other.components = [structuredClone(contact)];
other.components[0].id = 'other-contact';
other.wires = [];
p.pages.push(other);
const m1 = add(p, 'm1', 'motor_3phase', 300, 100), m2 = add(p, 'm2', 'motor_3phase', 400, 100);
m1.bmk = m2.bmk = '-M1';
const blank1 = add(p, 'blank1', 'contactor_coil'), blank2 = add(p, 'blank2', 'contactor_coil');
blank1.bmk = blank2.bmk = '';
const before = JSON.stringify(p), index = new ProjectIndex(p);
assert.equal(index.entry(coil)!.deviceKey, index.entry(contact)!.deviceKey);
assert.notEqual(index.entry(contact)!.deviceKey, index.entry(other.components[0])!.deviceKey);
assert.equal(index.identityIssues.filter(i => i.code === 'duplicate_device_tag').length, 1);
assert.equal(index.identityIssues.filter(i => i.code === 'missing_device_tag').length, 2);
assert(!index.deviceGroups.has(''));
assert.equal(index.entry(blank1)!.deviceKey, undefined);
assert.notEqual(scopedDesignation({ plant: 'AB', location: 'C' }, '-K'), scopedDesignation({ plant: 'A', location: 'BC' }, '-K'), 'Tuple keys cannot collide through string concatenation');
assert.equal(JSON.stringify(p), before, 'Building the index is read-only');
CrossReferenceEngine.updateProjectCrossReferences(p);
assert(contact.crossRef?.startsWith('/1.'));
assert(!other.components[0].crossRef);
assert.deepEqual(CrossReferenceEngine.getContactMirror(coil, p).map(m => m.slaveId), ['contact']);
assert.equal(referenceTargets(p, coil)[0].componentId, 'contact');
assert.equal(referenceTargets(p, structuredClone(coil))[0].componentId, 'contact', 'Properties-dialog copies retain navigation');
assert.equal(referenceTargets(p, { ...coil, bmk: '-Unassigned' })[0].componentId, undefined, 'An edited preview tag must not keep links to the old group');
const duplicate = structuredClone(coil);
duplicate.id = 'coil-copy';
p.pages[0].components.push(duplicate);
CrossReferenceEngine.updateProjectCrossReferences(p);
assert.equal(contact.crossRef, '');
assert.equal(CrossReferenceEngine.getContactMirror(coil, p).length, 0);
assert(new ProjectIndex(p).identityIssues.some(i => i.code === 'duplicate_master'));
p.pages[0].components.pop();
m2.mountingLocation = '+Different';
assert(!new ProjectIndex(p).identityIssues.some(i => i.code === 'duplicate_device_tag'), 'Rebuild sees mutable edits without stale cached groups');
const registry = new McpToolRegistry(), manager = { getProject: () => p } as any;
const response = await registry.executeTool('get_project_index', {}, manager);
assert(response.success);
assert.deepEqual(response.messages.items, collectPlausibilityMessages(p));
assert.equal(response.physicalDeviceCountKnown, false);
assert.deepEqual((await registry.executeTool('get_project_index', { offset: 1, limit: 1 }, manager)).messages.items, collectPlausibilityMessages(p).slice(1, 2));
// Independent strips share a visible name but never a structural identity.
const terminals = fixture();
terminals.pages[0].higherLevel = '=A';
terminals.pages[0].location = '+L';
const terminal = add(terminals, 't', 'terminal_single');
terminal.bmk = '-X1:7';
terminal.functionText = 'Verbraucher 99';
const sink = add(terminals, 'sink', 'contactor_coil');
sink.bmk = '-K2';
terminals.pages[0].wires = [{ id: 'w', from: { componentId: terminal.id, pinId: '1' }, to: { componentId: sink.id, pinId: 'A1' }, potential: 'L' }];
const tp = structuredClone(terminals.pages[0]);
tp.id = 't2';
tp.pageNumber = '2';
tp.location = '+Other';
tp.components = [structuredClone(terminal), structuredClone(sink)];
tp.components[0].id = 't-other';
tp.components[1].id = 'sink-other';
tp.wires = [];
terminals.pages.push(tp);
terminals.logicalConnections = [{ id: 'logical', from: { componentId: terminal.id, pinId: '2' }, to: { componentId: 'sink-other', pinId: 'A1' }, potential: 'L' }];
const ti = new ProjectIndex(terminals);
assert.equal(ti.connectionsFor(ti.entry(terminal)!).length, 2);
const strips = TerminalDiagramGenerator.generateTerminalReport(terminals);
assert.equal(strips.size, 2);
assert(strips.has('=A+L-X1'));
assert(strips.has('=A+Other-X1'));
const row = strips.get('=A+L-X1')![0];
assert.equal(row.terminalNumber, '7');
assert.equal(row.numberSource, 'designation');
assert.equal(row.internalTarget, '-K2:A1');
assert.equal(row.externalTarget, '=A+Other-K2:A1');
const duplicateIds = structuredClone(terminals);
duplicateIds.pages[1].components[1].id = 'sink';
const ambiguous = new ProjectIndex(duplicateIds);
assert.equal(ambiguous.component('sink'), undefined);
assert(ambiguous.identityIssues.some(i => i.code === 'duplicate_component_id'));
const numbered = fixture();
const n1 = add(numbered, 'n1', 'terminal_single'), n2 = add(numbered, 'n2', 'terminal_single');
n1.bmk = n2.bmk = '-X1';
assert(!new ProjectIndex(numbered).identityIssues.some(i => i.code === 'duplicate_terminal'));
n1.bmk = n2.bmk = '-X1:2';
assert(new ProjectIndex(numbered).identityIssues.some(i => i.code === 'duplicate_terminal'));
const repeatedPage = structuredClone(numbered.pages[0]);
numbered.pages.push(repeatedPage);
assert(new ProjectIndex(numbered).identityIssues.some(i => i.code === 'duplicate_page_id'));
assert.deepEqual([...new ProjectIndex(JSON.parse(JSON.stringify(p))).deviceGroups.keys()], [...new ProjectIndex(p).deviceGroups.keys()], 'No migration is required for a JSON roundtrip');
assert.equal((await registry.executeTool('get_project_index', { limit: 0 }, manager)).success, false);
console.log('✓ Shared project index: scoped identities, blank/ambiguous tags, project-owned ports, read-only snapshots, mutation rebuilds, UI/MCP parity, contact mirrors and structurally separate terminal reports');
