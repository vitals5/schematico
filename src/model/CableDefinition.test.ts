import assert from 'node:assert/strict';
import { CableDefinition, Page, Project, SymbolDefinition } from './types';
import { cableCrossings, cableDrawing } from './CableDefinition';
const symbol:SymbolDefinition={id:'end',name:'End',standard:'DIN EN 60617',category:'terminals',defaultBmkPrefix:'',defaultFunctionText:'',description:'',width:0,height:0,svgContent:'',pins:[{id:'1',name:'',x:0,y:0,direction:'bottom'}]};
const page={id:'p',components:[0,20].flatMap(x=>[0,100].map(y=>({id:`${x}-${y}`,symbolId:'end',bmk:'',functionText:'',x,y,rotation:(y===100?180:0) as 0|180,pins:{}}))),wires:[0,20].map(x=>({id:'w'+x,from:{componentId:`${x}-0`,pinId:'1'},to:{componentId:`${x}-100`,pinId:'1'},potential:'Signal'}))} as Page;
const project={pages:[page],symbolLibrary:[symbol],drawingUnitsPerMm:2} as Project;
const cable:CableDefinition={id:'c',start:{x:-10,y:50},end:{x:30,y:50},bmk:'-W1',cableType:'NYM-J',coreCount:2,crossSection:'1,5',cores:[{id:'c0',t:.25,color:'BU'}],markStyle:'slash'};
const before=JSON.stringify(page.wires);
assert.deepEqual(cableCrossings(cable,page,project).map(p=>p.wireIds),[['w0'],['w20']]);
const drawing=cableDrawing(cable,page,project);
assert.equal(drawing.filter(g=>g.kind==='line').length,3,'One bundle definition and two conductor marks');
assert(drawing.some(g=>g.kind==='text' && g.text==='2x1,5 mm²'));
assert(drawing.some(g=>g.kind==='text' && g.text==='BU'));
assert.equal(JSON.stringify(page.wires),before,'A cable annotation never changes the electrical graph');
cable.start={x:50,y:-10};cable.end={x:50,y:110};
assert.equal(cableCrossings(cable,page,project).length,0,'Parallel conductors are not collected');
cable.start={x:-10,y:100};cable.end={x:30,y:100};
assert.equal(cableCrossings(cable,page,project).length,2,'Wire endpoint intersections count once');
console.log('✓ Cable bundles collect crossed wires, render metadata and remain electrically independent');
