import assert from 'node:assert/strict';
import 'fake-indexeddb/auto';
import { ArticleCatalog, catalogKey, catalogRevision, catalogToCsv, parseCatalogFile, validateCatalogArticle } from './ArticleCatalog';
import { editorArticles, loadLocalEditorArticles, mergeEditorArticles, onEditorArticlesChange, assignMainCatalogArticle } from './EditorArticles';
import { refreshSharedCatalog } from './GitHubCatalog';
import { appendPublicArticle, validatePublicArticle } from '../shared/catalog-publication.mjs';
import { effectiveArticles, setArticleAssignment } from './ArticleAssignments';
import { fixture, add } from '../layout/testing/fixture';
import { CadCanvas } from '../editor/CadCanvas';
import { ProjectHistory } from './ProjectHistory';
const record = validateCatalogArticle({articleNumber:'CENTRAL-7',manufacturer:'New maker <&>',variant:'A',description:'New public article',origin:'user',verification:'unverified'});
const envelope = {schema:'schematico-articles',version:1,articles:[record]};
await refreshSharedCatalog((async () => Response.json(envelope)) as typeof fetch);
assert(editorArticles().some(e => catalogKey(e.article) === record.id), 'All published records appear, including those without a symbol');
assert.equal(editorArticles().find(e => e.article.id === record.id)!.symbolId,undefined);
const linked = validateCatalogArticle({...record,symbolId:'rcd_4p'});
const local = new ArticleCatalog();
let notifications = 0;
const stop = onEditorArticlesChange(() => { notifications++; });
await local.merge([linked],false,catalogRevision(await local.list()));
await loadLocalEditorArticles();
assert.equal(editorArticles().find(e => e.article.id === record.id)!.symbolId,'rcd_4p');
assert(notifications>0);
assert.equal((await new ArticleCatalog().list())[0].symbolId,'rcd_4p');
assert.equal(mergeEditorArticles([record],[linked]).filter(e => e.article.id === record.id).length,1);
assert.equal(mergeEditorArticles([record],[validateCatalogArticle({...record,variant:'B',symbolId:'rcd_2p'})]).filter(e=>e.article.articleNumber===record.articleNumber).length,2);
const seed = mergeEditorArticles([],[])[0];
assert(seed.symbolId, 'Existing starter symbol mapping survives an old shared catalogue');
assert.equal(mergeEditorArticles([{...seed.article,symbolId:undefined}],[]).find(e=>e.article.id===seed.article.id)!.symbolId,seed.symbolId);
assert.equal(mergeEditorArticles([],[{...seed.article,symbolId:undefined}]).find(e=>e.article.id===seed.article.id)!.symbolId,undefined,'Explicit local removal must not revive the starter symbol');
for(const symbolId of [123,{},'x'.repeat(257),'bad\nkey'])assert.throws(()=>validateCatalogArticle({...record,symbolId}));
assert.equal(validatePublicArticle(linked).symbolId,'rcd_4p');
assert.equal(parseCatalogFile(catalogToCsv([linked]),'csv')[0].symbolId,'rcd_4p');
const published = appendPublicArticle({...envelope,articles:[]},linked).catalog;
assert.equal(published.articles[0].symbolId,'rcd_4p');
assert.equal(appendPublicArticle(published,linked).changed,false);
assert.throws(()=>appendPublicArticle(published,{...linked,symbolId:'rcd_2p'}),/githubCatalogConflict/);
const project = fixture(), component = add(project,'existing','terminal_single',55,65);
setArticleAssignment(component,[{articleNumber:'old',manufacturer:'Old',variant:'',role:'main',quantity:2},{articleNumber:'accessory',manufacturer:'Old',variant:'',role:'accessory',quantity:3}]);
const geometry = JSON.stringify([component.symbolId,component.x,component.y,component.pins,project.pages[0].wires]);
assignMainCatalogArticle(component,linked,project);
assert.equal(JSON.stringify([component.symbolId,component.x,component.y,component.pins,project.pages[0].wires]),geometry);
assert.equal(effectiveArticles(component,project)[1].quantity,3);
assert.equal(effectiveArticles(component,project)[0].quantity,2);
assert.deepEqual(effectiveArticles(component,project)[0].snapshot,linked);
const oldComponent = JSON.stringify(component);
const history = new ProjectHistory();history.reset(project);
let selectionSawSnapshot=false;
const canvas:any = Object.assign(Object.create(CadCanvas.prototype),{project,activePage:project.pages[0],autoconnectEnabled:false,
  clearMultipleSelection:()=>{},cancelBoxInteraction:()=>{},setElementSelection:()=>{},render:()=>{},placementPosition:(x:number,y:number)=>({x,y}),
  notifyModified:()=>history.record(project),callbacks:{onSelectComponent:(c:any)=>{selectionSawSnapshot=!!c.articleAssignment?.items[0].snapshot;}}});
canvas.setArticleToPlace(editorArticles().find(e=>e.article.id===record.id)!);
const placed=canvas.placeSymbolAt(160,120);
assert(selectionSawSnapshot,'Article data must be present before selection callbacks and the first history snapshot');
assert.equal(placed.symbolId,'rcd_4p');assert.equal(placed.articleNumber,record.articleNumber);
assert.equal(JSON.stringify(component),oldComponent,'Choosing a part cannot modify the previously selected symbol');
assert.deepEqual(history.redo(),undefined);
const undone=history.undo()!;assert.equal(undone.pages[0].components.length,1);
assert.equal(history.redo()!.pages[0].components[1].articleAssignment!.items[0].snapshot!.symbolId,'rcd_4p');
const second=canvas.placeSymbolAt(260,120);assert.equal(second.articleNumber,record.articleNumber);assert.notEqual(second.id,placed.id);
canvas.setSymbolToPlace('terminal_single');
assert.equal(canvas.placeSymbolAt(350,120).articleAssignment,undefined,'Ordinary symbol placement must not inherit the last article');
assert.throws(()=>canvas.setArticleToPlace({...seed,symbolId:'missing-library-symbol'}),/articleSymbolMissing/);
linked.description='external mutation';assert.equal(placed.articleAssignment.items[0].snapshot.description,record.description);
await local.remove(record.id,catalogRevision(await local.list()));await loadLocalEditorArticles();
assert.equal(editorArticles().find(e=>e.article.id===record.id)!.symbolId,undefined,'Removing a local override reveals the public record again');
// Verify that an article with a CAD symbol from symbols.json resolves packageSymbol
const eltakoArticle = editorArticles().find(e => e.article.articleNumber === '21400301');
if (eltakoArticle) {
  assert(eltakoArticle.packageSymbol, 'ELTAKO article has packageSymbol resolved from shared symbols.json');
  assert.equal(eltakoArticle.packageSymbol.pins.length, 20);
}

stop();
console.log('✓ Shared/local editor catalogue, variant identity, symbol linkage, CSV/public validation, preserved geometry/accessories, atomic repeated placement, snapshot isolation, undo/redo and ordinary-symbol reset');
