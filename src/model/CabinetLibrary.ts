export function cabinetStandard(id: unknown): CabinetStandard | undefined {
  return typeof id === "string" ? byId.get(id) : undefined;
}
export function findCabinetStandards(
  query: string,
  category: CabinetLibraryCategory | "" = "",
) {
  const words = query.toLocaleLowerCase().trim().split(/\s+/).filter(Boolean);
  return cabinetStandardLibrary.filter(
    (d) =>
      (!category || d.category === category) &&
      words.every((w) =>
        `${d.name.de} ${d.name.en} ${d.badge} ${d.keywords}`
          .toLocaleLowerCase()
          .includes(w),
      ),
  );
}
