/** Generic mechanical planning shapes. Dimensions are editable defaults, not product data. */
export type CabinetLibraryCategory =
  | "protection"
  | "switching"
  | "distribution"
  | "supply"
  | "automation"
  | "drives"
  | "accessories";
export type CabinetFace =
  | "breaker"
  | "rcd"
  | "fuse"
  | "surge"
  | "switch"
  | "contactor"
  | "relay"
  | "meter"
  | "power"
  | "plc"
  | "terminal"
  | "earth"
  | "neutral"
  | "socket"
  | "blank"
  | "drive"
  | "fan"
  | "light";
export interface CabinetStandard {
  readonly id: string;
  readonly category: CabinetLibraryCategory;
  readonly name: { readonly de: string; readonly en: string };
  readonly face: CabinetFace;
  readonly badge: string;
  readonly prefix: string;
  readonly widthMm: number;
  readonly heightMm: number;
  readonly poles: number;
  readonly modules?: number;
  readonly railMount: boolean;
  readonly keywords: string;
}
export const cabinetLibraryCategories: readonly CabinetLibraryCategory[] = [
  "protection",
  "switching",
  "distribution",
  "supply",
  "automation",
  "drives",
  "accessories",
];
function part(
  id: string,
  category: CabinetLibraryCategory,
  de: string,
  en: string,
  face: CabinetFace,
  badge: string,
  prefix: string,
  widthMm: number,
  heightMm: number,
  poles = 1,
  railMount = true,
  keywords = "",
  modules?: number,
): CabinetStandard {
  return Object.freeze({
    id,
    category,
    name: Object.freeze({ de, en }),
    face,
    badge,
    prefix,
    widthMm,
    heightMm,
    poles,
    railMount,
    keywords,
    ...(modules ? { modules } : {}),
  });
}
function modular(
  id: string,
  category: CabinetLibraryCategory,
  de: string,
  en: string,
  face: CabinetFace,
  badge: string,
  prefix: string,
  modules: number,
  poles = 1,
  keywords = "",
) {
  return part(
    id,
    category,
    de,
    en,
    face,
    badge,
    prefix,
    modules * 18,
    90,
    poles,
    true,
    keywords,
    modules,
  );
}
