import assert from 'node:assert/strict';
import type { Page, PageBox, Project } from './types';
import { boxDrawing, boxSvg } from './DeviceBox';
import { elementsInWindow, captureSelectionMove, translateSelection, selectionCount, normalizeSelection } from './ElementSelection';
import { applySelectionProperties, sharedPropertyValue } from './SelectionProperties';
import { ProjectHistory } from './ProjectHistory';
import { MacroManager } from './MacroManager';
import { nextDeviceTag } from './DeviceTag';
import { PdfExporter } from '../export/PdfExporter';

const box:PageBox={id:'frame',kind:'device',bmk:'-A1',x:80,y:80,width:160,height:96,lineStyle:'solid',lineWidth:.8,fontSize:6,label:'Steuergerät <A>\nZweite Zeile',description:'Längerer Beschreibungstext für einen schmalen Rahmen'};
const legacy:PageBox={id:'imported',x:400.25,y:100.75,width:120.125,height:80.5,label:'Importierter Bereich'};
assert.equal(boxDrawing(box)[0].kind,'rect');assert(!('dash' in boxDrawing(box)[0]));
const dashed={...box,lineStyle:'dashed' as const};assert.deepEqual((boxDrawing(dashed)[0] as any).dash,[4,3]);
assert.deepEqual((boxDrawing(legacy)[0] as any).dash,[4,3],'Legacy imported frames retain dashed lines');
for(const g of boxDrawing(box))if(g.kind==='text'){
  assert(g.x>=box.x&&g.y<box.y+box.height);assert(g.text.length<=Math.floor((box.width-12)/(g.size*.65)),'Labels wrap inside the frame');
}
assert.equal(boxDrawing({...box,width:1}).filter(g=>g.kind==='text').length,0,'Frames too narrow for one glyph keep the text in properties without spilling');
assert.match(boxSvg(box,true),/pointer-events="stroke"/,'Only the border intercepts pointer events');
assert.match(boxSvg(box,true),/Steuergerät &lt;A&gt;/,'Labels are escaped');
assert.match(boxSvg(box,true),/data-box-resize="frame"/);
const page={id:'p',title:'Gerätekästen',pageNumber:'1',components:[],wires:[],boxes:[box,legacy],plotFrame:{type:'DIN_A3_LANDSCAPE',width:1000,height:700,titleBlock:{}}} as unknown as Page;
const project={id:'test',name:'Gerätekästen',pages:[page],activePageId:'p',drawingUnitsPerMm:2} as Project;
const selection=elementsInWindow(page,project,{x:70,y:70},{x:250,y:190});
assert.deepEqual(selection.boxIds,['frame']);assert.equal(selectionCount(selection),1);
assert.deepEqual(normalizeSelection(page,{componentIds:[],cableIds:[],boxIds:['frame','frame','missing']}).boxIds,['frame']);
const original=JSON.stringify(project),history=new ProjectHistory();history.reset(project);
const move=captureSelectionMove(page,selection);translateSelection(page,move,16,24);translateSelection(page,move,32,48);
assert.deepEqual([box.x,box.y],[112,128]);assert.equal(legacy.x,400.25);assert.equal(box.width,160);
history.record(project);assert.deepEqual(JSON.parse(JSON.stringify(history.undo())),JSON.parse(original));assert.equal(history.redo()!.pages[0].boxes![0].x,112);
const group={componentIds:[],cableIds:[],boxIds:['frame','imported']};
assert.equal(sharedPropertyValue(page,project,group,'boxLineStyle'),undefined);
assert(applySelectionProperties(page,project,group,{boxLineStyle:'dashed',boxFontSize:2.5,boxLineWidth:.3}));
assert.equal(box.fontSize,5);assert.equal(legacy.fontSize,5);assert.equal(box.lineWidth,.6);assert.equal(legacy.lineStyle,'dashed');
const beforeBad=JSON.stringify(page);assert.throws(()=>applySelectionProperties(page,project,group,{boxFontSize:2,boxLineWidth:0}));assert.equal(JSON.stringify(page),beforeBad,'Invalid combined edits are atomic');
assert.equal(nextDeviceTag(project,'-A'),'-A2','Device frames reserve BMKs alongside ordinary devices');
const saved=JSON.parse(JSON.stringify(project)) as Project;assert.deepEqual(saved.pages[0].boxes,page.boxes);
// A page macro, portable file and window placement retain actual editable box objects.
const macro=MacroManager.createMacroFromPage(page),source=JSON.stringify(macro),prepared=MacroManager.forPlacement(macro);
assert.equal(JSON.stringify(macro),source);assert.equal(prepared.components.length,1);assert.equal(prepared.boxes!.length,1);
assert.match(MacroManager.generateMacroSvgThumbnail(prepared),/<rect/);
const exported=MacroManager.exportMacro(prepared),parsed=await MacroManager.parseMacroFile(new File([exported.blob],exported.filename));
assert.equal(parsed.type,'ema');if(parsed.type!=='ema')throw new Error('Expected window macro');
assert.deepEqual(parsed.boxes,prepared.boxes);
const destination={...project,drawingUnitsPerMm:4};
const placed=MacroManager.instantiateWindowMacro(parsed,320,160,[],destination);
assert.equal(placed.boxes.length,1);assert.equal(placed.components.length,1);
assert.equal(placed.components[0].deviceBox!.width,320);assert.equal(placed.components[0].bmkPosition!.fontSize,10);assert.equal(placed.components[0].deviceBox!.lineWidth,1.2);
assert.equal(placed.components[0].deviceBox!.lineStyle,'dashed');assert.equal(placed.components[0].bmk,'-A2');assert.notEqual(placed.components[0].id,box.id);
assert(placed.components[0].additionalText!.includes(box.description!));
const pdf:any={},rects:number[][]=[],patterns:number[][]=[],texts:string[]=[];
for(const name of ['setDrawColor','setTextColor','setLineWidth','setFont','setFontSize','setFillColor'])pdf[name]=()=>{};
pdf.setLineDashPattern=(pattern:number[])=>patterns.push(pattern);pdf.rect=(...args:number[])=>rects.push(args);pdf.text=(value:string)=>texts.push(value);
(PdfExporter as any).renderBoxes(pdf,page,420,297,'monochrome');
assert.equal(rects.length,2);assert.equal(rects[0][0],box.x*420/1000);assert.equal(rects[0][2],box.width*420/1000);
assert(patterns.some(pattern=>pattern.length===2),'Dashed frame reaches actual PDF renderer');
assert(texts.includes('-A1')&&texts.includes('Steuergerät <A>'));
console.log('✓ Editable device frames: line styles, wrapped labels, stroke-only hit area, selection, relative movement, undo, shared properties, BMK uniqueness, JSON, portable macro scaling and PDF vectors');
