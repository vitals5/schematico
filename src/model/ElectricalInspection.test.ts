import assert from 'node:assert/strict';
import { fixture, add } from '../layout/testing/fixture';
import { inspectElectricalProject } from './ElectricalInspection';
import { collectPlausibilityMessages } from './ProjectInspection';
import { ProjectIndex } from './ProjectIndex';
import { ElectricalNetService } from './ElectricalNetService';
import { McpToolRegistry } from '../ai/mcp-tools';
import { PackageHandler } from '../packages/PackageHandler';
import { setUiLanguage } from '../i18n';
import { collectInspectionFields, applyInspectionFields, renderInspectionFields } from '../ui/InspectionFields';
const project = fixture(), socket = add(project, 'socket', 'socket_schuko'), coil = add(project, 'coil', 'contactor_coil');
socket.articleRequirement = 'none';
coil.articleRequirement = 'required';
socket.pins['1'].connectionRequirement = 'required';
socket.pins.N.connectionRequirement = 'reserve';
socket.pins.PE.connectionRequirement = 'optional';
let report = inspectElectricalProject(project);
assert(report.messages.some(m => m.ruleId === 'required_pin_open' && m.location.pinId === '1'));
assert(!report.messages.some(m => m.componentId === socket.id && m.ruleId === 'unwired'));
assert(!report.messages.some(m => m.componentId === socket.id && m.ruleId === 'missing_article'));
assert(report.messages.some(m => m.componentId === coil.id && m.ruleId === 'missing_article' && m.severity === 'warning'));
project.pages[0].wires = [{ id: 'wire', from: { componentId: socket.id, pinId: '1' }, to: { componentId: coil.id, pinId: 'A1' }, potential: 'arbitrary label' }];
report = inspectElectricalProject(project);
assert(!report.messages.some(m => m.ruleId === 'required_pin_open'));
project.pages[0].wires.push({ id: 'reserve', from: { componentId: socket.id, pinId: 'N' }, to: { componentId: coil.id, pinId: 'A2' }, potential: 'Signal' });
assert(inspectElectricalProject(project).messages.some(m => m.ruleId === 'reserve_pin_connected'));
socket.pins['1'].potentialConstraint = 'L1';
coil.pins.A1.potentialConstraint = 'L2';
report = inspectElectricalProject(project);
const conflict = report.messages.find(m => m.ruleId === 'potential_conflict')!;
assert(conflict);
assert.equal(conflict.relatedLocations.length, 2);
assert(conflict.location.netId);
socket.pins['1'].customLabel = 'anything';
coil.pins.A1.customLabel = 'anything';
assert.equal(inspectElectricalProject(project).messages.find(m => m.ruleId === 'potential_conflict')!.id, conflict.id);
coil.pins.A1.potentialConstraint = 'L1';
assert(!inspectElectricalProject(project).messages.some(m => m.ruleId === 'potential_conflict'));
// An obsolete placement pin is not a valid declared library port.
socket.pins.typo = {};
project.pages[0].wires.push({ id: 'bad', from: { componentId: coil.id, pinId: 'A1' }, to: { componentId: socket.id, pinId: 'typo' }, potential: 'N' });
report = inspectElectricalProject(project);
const invalid = report.messages.find(m => m.ruleId === 'invalid_endpoint')!;
assert.equal(invalid.location.componentId, socket.id);
assert.equal(invalid.location.pinId, 'typo');
assert.equal(invalid.location.wireId, 'bad');
const idx = new ProjectIndex(project), nets = new ElectricalNetService(idx);
assert(!nets.hasConnection(idx.pin(idx.entry(socket)!, 'typo')!));
const before = JSON.stringify(project), ids = report.messages.map(m => m.id);
assert.deepEqual(collectPlausibilityMessages(project), report.messages);
assert.equal(JSON.stringify(project), before);
setUiLanguage('en');
for (const c of project.pages[0].components) {
    c.x += 100;
    c.y += 200;
    c.rotation = 180;
}
project.pages[0].components.reverse();
project.pages[0].wires.reverse();
assert.deepEqual(inspectElectricalProject(project).messages.map(m => m.id), ids, 'IDs do not depend on locale, drawing order or marker coordinates');
setUiLanguage('de');
// Physical reserve/required policies concern actual port occupation, not internal bridge reachability.
const terminalProject = fixture(), terminal = add(terminalProject, 't', 'terminal_single'), sink = add(terminalProject, 'sink', 'contactor_coil');
terminalProject.pages[0].wires = [{ id: 'one', from: { componentId: terminal.id, pinId: '1' }, to: { componentId: sink.id, pinId: 'A1' }, potential: 'N' }];
terminal.pins['2'].connectionRequirement = 'reserve';
assert(!inspectElectricalProject(terminalProject).messages.some(m => m.ruleId === 'reserve_pin_connected'));
terminal.pins['2'].connectionRequirement = 'required';
assert(inspectElectricalProject(terminalProject).messages.some(m => m.ruleId === 'required_pin_open' && m.location.pinId === '2'));
// Optional unpaired continuation is allowed; explicit required continuation and stale printed target are diagnosed.
const arrow = add(project, 'arrow', 'potential_arrow_up');
arrow.bmk = 'OUT';
arrow.referenceRequirement = 'optional';
assert(!inspectElectricalProject(project).messages.some(m => m.componentId === arrow.id));
arrow.referenceRequirement = 'required';
assert(inspectElectricalProject(project).messages.some(m => m.ruleId === 'missing_reference_target'));
arrow.crossRef = '/missing.2';
assert(inspectElectricalProject(project).messages.some(m => m.ruleId === 'unresolved_reference'));
const contact = add(project, 'contact', 'contact_no');
contact.bmk = coil.bmk;
coil.articleNumber = 'PART';
assert(!inspectElectricalProject(project).messages.some(m => m.componentId === contact.id && ['missing_master_reference', 'missing_article'].includes(m.ruleId)));
contact.mountingLocation = '+Elsewhere';
assert(inspectElectricalProject(project).messages.some(m => m.componentId === contact.id && m.ruleId === 'missing_master_reference'));
// UI, standalone MCP, existing MCP tools and import return the same causes and IDs.
const registry = new McpToolRegistry(), manager = { getProject: () => project } as any;
report = inspectElectricalProject(project);
const response = await registry.executeTool('validate_electrical_project', {}, manager);
assert(response.success);
assert.deepEqual(response.messages.items, report.messages);
assert.equal(response.domain, 'electrical');
assert.deepEqual((await registry.executeTool('get_project_index', {}, manager)).messages.items, report.messages);
assert.deepEqual((await registry.executeTool('get_electrical_nets', { limit: 100 }, manager)).messages.items, report.messages);
assert.deepEqual((await registry.executeTool('validate_electrical_project', { offset: 1, limit: 2 }, manager)).messages.items, report.messages.slice(1, 3));
const imported = await PackageHandler.inspectFile(new File([JSON.stringify(project)], 'inspection.json', { type: 'application/json' }));
assert.deepEqual(imported.electricalInspection?.messages, inspectElectricalProject(imported.extractedProject!).messages);
// Editing only a policy does not overwrite the label, other ports, or other mixed policies.
const a = structuredClone(socket), b = structuredClone(socket);
b.pins['1'].customLabel = 'other label';
b.referenceRequirement = 'optional';
const draft = structuredClone(a), id = 'inspection-connectionRequirement-1', dirty = new Set([id]);
const input = { id, value: 'reserve', dataset: { inspectionControl: 'connectionRequirement', inspectionPin: '1' } };
collectInspectionFields({ querySelectorAll: () => [input] } as any, draft, dirty);
applyInspectionFields(draft, b, dirty);
assert.equal(b.pins['1'].connectionRequirement, 'reserve');
assert.equal(b.pins['1'].customLabel, 'other label');
assert.equal(b.referenceRequirement, 'optional');
input.value = '';
collectInspectionFields({ querySelectorAll: () => [input] } as any, draft, dirty);
applyInspectionFields(draft, b, dirty);
assert.equal(b.pins['1'].connectionRequirement, undefined);
assert(renderInspectionFields(a, [a, b], project, new Set()).includes('__mixed'));
console.log('✓ Shared electrical inspection: stable causes and locations, port policies, explicit constraints, references, master articles, editor/MCP/import parity and non-destructive policy edits');
