import assert from 'node:assert/strict';
import { defaultPlotFrame, frameTextCell, frameTextValue, fitFrameText, plotFrameSvg } from './PlotFrame';
import { Page, Project } from './types';
const template=defaultPlotFrame();
const page={id:'p',title:'Wohnzimmer',pageNumber:'21-1',higherLevel:'=HAUS',location:'+EG',plotFrame:{width:1000,height:297*1000/420,titleBlock:{company:'Firma & Partner',projectTitle:'Haus',author:'A',date:'17.10.2026'}}} as Page;
const project={pages:[page],description:'Haus',company:'Firma',plotFrameTemplate:template} as Project;
assert.equal(frameTextValue(template.texts.find(t=>t.property===11011)!,page,project,template),'Wohnzimmer');
assert.equal(frameTextValue(template.texts.find(t=>t.id==='location')!,page,project,template),'EG');
const title=template.texts.find(t=>t.property===11011)!;
const cell=frameTextCell(title,template);
assert.equal(cell.x,230.3);assert.equal(cell.width,69.4);
const fit=fitFrameText('Sehr lange Raumbezeichnung mit mehreren Zusatzangaben und Bauteilbezeichnungen für einen Plankopf',title,cell);
assert(fit.lines.length>1 || fit.size<title.size);
assert(fit.y-fit.size>=cell.y-1e-6);
assert(fit.y+(fit.lines.length-1)*fit.size*1.2<=cell.y+cell.height);
page.title='<Raum & Text> '.repeat(40);
const svg=plotFrameSvg(page,project);
assert.match(svg,/clipPath/);assert.match(svg,/clip-path="url\(#frame-clip-page-title\)"/);
assert(!svg.includes('<Raum & Text>'));
assert.match(svg,/Firma &amp; Partner/);
console.log('✓ Shared norm-sheet fields, wrapping, escaping and bounded title text');
